import { test, expect } from '@playwright/test';
import { mockHome } from './support/home';
import { mockWeekly } from './support/weekly';

test('daily home edits expense and income from an earlier month and refreshes the selected day', async ({ page }) => {
  const id = '00000000-0000-4000-8000-000000000456';
  const date = '2026-09-20';
  const jwt = [btoa(JSON.stringify({ alg: 'HS256', typ: 'JWT' })), btoa(JSON.stringify({ sub: id, exp: Math.floor(Date.now()/1000)+3600, aud: 'authenticated', role: 'authenticated' })), 'mock'].join('.');
  await page.addInitScript(({ id, jwt }) => localStorage.setItem('sb-mfdttuvsvplbrfmjxxqs-auth-token', JSON.stringify({ access_token: jwt, refresh_token: 'mock', token_type: 'bearer', expires_at: Math.floor(Date.now()/1000)+3600, user: { id, aud: 'authenticated', role: 'authenticated', email: 'test@moneyspace.invalid', app_metadata: {}, user_metadata: {}, created_at: new Date().toISOString() } })), { id, jwt });
  const rows = [
    { id: 'expense', kind: 'expense', amount: '80.00', merchant: 'อาหาร', category_id: 'food' },
    { id: 'income', kind: 'income', amount: '500.00', merchant: 'รายรับ', category_id: null },
  ].map(t => ({ ...t, owner_id: id, account_id: 'account', destination_account_id: null, household_id: null, envelope_id: null, notes: null, tag: 'need', occurred_on: date, refund_of_id: null, updated_at: date+'T00:00:00Z', created_at: date+'T00:00:00Z', deleted_at: null, income_category_code: null as string|null, category_name_snapshot: null as string|null }));
  const state = { month: '2026-11-01', current_period_exists: true, accounts: [{ id: 'account', name: 'เงินรวม', kind: 'bank', balance: '420.00', opening_balance: '0' }], categories: [{ id: 'food', name: 'อาหาร', icon: '🍜', tag: 'need', envelope: null }], envelopes: [], goals: [], contributions: [], income: '500.00', expenses: '80.00', cash: '420.00', savings: '0', transactions: [] as Record<string,unknown>[], transaction_count: 0 };
  await mockWeekly(page);
  await page.route('**/rest/v1/profiles*', r => r.fulfill({ json: { display_name: 'tape', onboarding_completed_at: date+'T00:00:00Z' } }));
  await page.route('**/rest/v1/rpc/moneyspace_snapshot_v2', r => r.fulfill({ json: state }));
  await mockHome(page, () => ({ ...state, transactions: rows }));
  let failRead = true;
  await page.route('**/rest/v1/transactions?*', r => {
    const url = new URL(r.request().url());
    expect(url.searchParams.get('owner_id')).toBe('eq.'+id);
    expect(url.searchParams.get('deleted_at')).toBe('is.null');
    if (failRead) return r.fulfill({ status: 403, json: { message: 'unavailable' } });
    return r.fulfill({ json: rows.find(t => 'eq.'+t.id === url.searchParams.get('id')) });
  });
  let writes = 0;
  let additions = 0;
  await page.route(/\/rest\/v1\/rpc\/moneyspace_write(?:_income)?$/, r => {
    const { p_action, p_data } = r.request().postDataJSON();
    if(p_action==='add_transaction'){
      expect(p_data.kind).toBe('income');expect(p_data.income_category_code).toBe('salary');
      rows.push({...rows[1],id:'income-new',merchant:'เงินเดือน',amount:p_data.amount,income_category_code:'salary',category_name_snapshot:'เงินเดือน',occurred_on:p_data.date});
      state.income=String(Number(state.income)+Number(p_data.amount));state.cash=(Number(state.income)-Number(state.expenses)).toFixed(2);additions++;
      return r.fulfill({json:{confirmed:true,id:'income-new',action:p_action}});
    }
    expect(p_action).toBe('edit_transaction');
    const row = rows.find(t => t.id === p_data.id)!;
    expect(p_data.version).toBe(row.updated_at);
    expect(p_data.date).toBe(date);
    row.amount = p_data.amount;
    if(row.kind==='income'){expect(p_data.income_category_code).toBe('freelance');row.income_category_code=p_data.income_category_code;row.category_name_snapshot='รับจ้าง';}
    row.updated_at = date+'T01:00:00Z';
    writes++;
    state.expenses = rows[0].amount; state.income = rows[1].amount;
    state.cash = (Number(state.income)-Number(state.expenses)).toFixed(2);
    return r.fulfill({ json: { confirmed: true, id: row.id, action: p_action } });
  });
  const errors: string[] = [];page.on('pageerror', e => errors.push(e.message));
  await page.goto('/');
  const dateInput = page.locator('.home-date-toolbar input[type=date]');
  const initialDate = await dateInput.inputValue();
  await page.getByRole('button',{name:'เปิดปฏิทิน',exact:true}).click();
  await expect(page.getByRole('dialog')).toContainText('สมุดรอยเท้ารับ–จ่าย');
  await expect(page.locator('.calendar-footnote')).toBeVisible();
  await expect(page.locator('.duck-calendar-grid button.selected')).toHaveAttribute('aria-label',initialDate+' มีรายการ 1 รายการ');
  await page.screenshot({animations:'disabled',path:'artifacts/'+test.info().project.name+'-duck-calendar.png'});
  await page.locator('.duck-calendar-grid button.selected').click();
  await dateInput.fill(date);
  await page.getByRole('button', { name: 'ดูและแก้ไข อาหาร', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('เปิดรายการไม่ได้');
  await expect(page.getByRole('dialog')).toHaveCount(0);
  failRead = false;
  for (const [name, value] of [['อาหาร', '90.50'], ['รายรับ', '600.00']]) {
    await page.getByRole('button', { name: 'ดูและแก้ไข '+name, exact: true }).click();
    await expect(page.getByRole('dialog')).toContainText('รายละเอียดรายการ');
    await page.getByRole('button', { name: 'แก้ไข', exact: true }).click();
    await page.getByLabel('จำนวนเงิน (บาท)', { exact: true }).fill(value);
    if(name==='รายรับ')await page.getByRole('button',{name:'รับจ้าง',exact:true}).click();
    await page.getByRole('dialog').getByRole('button', { name: 'บันทึก', exact: true }).click();
    await expect(page.getByRole('dialog')).toHaveCount(0);
    await expect(dateInput).toHaveValue(date);
    await expect(page.getByRole('button', { name: 'ดูและแก้ไข '+name, exact: true })).toContainText(value);
  }
  await expect(page.locator('.page-heading')).toHaveCount(0);
  await expect(page.locator('.quick-action-grid')).toHaveCount(0);
  const targetInput = page.getByLabel('เป้ารายวัน (บาท)', {exact:true});
  await expect(targetInput).toHaveValue('150.00');
  let rejectTarget = true;
  await page.route('**/rest/v1/rpc/moneyspace_daily_target', route => rejectTarget ? route.fulfill({status:403,json:{message:'denied'}}) : route.fallback());
  await targetInput.fill('200.50');
  await page.getByRole('button',{name:'ตั้งเป้า',exact:true}).click();
  await expect(page.getByRole('alert')).toContainText('ยังไม่ได้ยืนยันเป้ารายวัน');
  await expect(page.getByRole('meter')).toHaveAttribute('aria-valuenow','60');
  rejectTarget = false;
  await page.getByRole('button',{name:'ตั้งเป้า',exact:true}).click();
  await expect(page.getByRole('meter')).toHaveAttribute('aria-valuenow','45');
  await page.reload();
  await expect(targetInput).toHaveValue('200.50');
  await expect(page.getByTestId('actual-expenses')).toContainText('90.50');
  await page.getByRole('button',{name:'เพิ่มรายการ',exact:true}).filter({visible:true}).first().click();
  await expect(page.getByRole('dialog')).toContainText('จดอะไรดี');
  await page.screenshot({animations:'disabled',path:'artifacts/'+test.info().project.name+'-entry-menu.png'});
  await page.getByRole('button',{name:'รายได้',exact:true}).click();
  await expect(page.getByRole('dialog')).toContainText('บันทึกรายรับ');
  await page.getByLabel('จำนวนเงิน (บาท)',{exact:true}).fill('1000');
  await page.getByRole('dialog').getByRole('button',{name:'บันทึก',exact:true}).click();
  await expect(page.getByRole('dialog').getByRole('alert')).toContainText('เลือกหมวดรายได้');
  await page.getByRole('button',{name:'เงินเดือน',exact:true}).click();
  await page.screenshot({animations:'disabled',path:'artifacts/'+test.info().project.name+'-income-categories.png',fullPage:true});
  await page.getByRole('dialog').getByRole('button',{name:'บันทึก',exact:true}).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await expect(page.getByRole('button',{name:'ดูและแก้ไข เงินเดือน',exact:true})).toContainText('1,000.00');
  await page.getByRole('button',{name:'เพิ่มรายการ',exact:true}).filter({visible:true}).first().click();
  await page.getByRole('button',{name:'กันออม',exact:true}).click();
  await expect(page.getByRole('dialog')).toContainText('สร้างเป้าหมายเงินออม');
  await page.getByRole('button',{name:'ปิด',exact:true}).click();
  await expect(page.locator('.dialog-overlay')).toHaveCount(0);
  await page.screenshot({animations:'disabled',path:'artifacts/'+test.info().project.name+'-compact-home.png',fullPage:true});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.getByRole('button',{name:'ดูและแก้ไข รายรับ',exact:true}).click();
  await expect(page.getByRole('dialog')).toContainText('รับจ้าง');
  await page.getByRole('button',{name:'แก้ไข',exact:true}).click();
  await expect(page.getByRole('button',{name:'รับจ้าง',exact:true})).toHaveAttribute('aria-pressed','true');
  await page.getByRole('button',{name:'ปิด',exact:true}).click();
  expect(writes).toBe(2);
  expect(additions).toBe(1);
  await page.getByRole('tab',{name:'รายสัปดาห์',exact:true}).click();
  await page.getByRole('button',{name:'น้องช่วยอ่านกราฟ',exact:true}).click();
  await expect(page.locator('.duck-speech')).toContainText('รายจ่ายสุทธิที่จด');
  await expect(page.getByRole('img',{name:'กราฟย่อรายจ่ายสุทธิรายวัน'})).toBeVisible();
  await page.getByRole('button',{name:'การ์ดสรุปสัปดาห์',exact:true}).click();
  await expect(page.getByAltText('ตัวอย่างการ์ดสัปดาห์ที่ซ่อนยอดเงิน')).toBeVisible();
  await page.getByLabel('แสดงยอดเงินบนการ์ดแชร์').check();
  await expect(page.getByAltText('ตัวอย่างการ์ดสัปดาห์ที่แสดงยอดเงิน')).toBeVisible();
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button',{name:'บันทึกรูป PNG',exact:true}).click();
  const download = await downloadPromise;
  expect(download.suggestedFilename()).toMatch(/\.png$/);
  expect(await download.failure()).toBeNull();
  expect(errors).toEqual([]);
});
